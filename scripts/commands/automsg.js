module.exports.onLoad = o => {
    const moment = require("moment-timezone");
    let lastSent = null;

    setInterval(() => {
        // Asia/Dhaka = Bangladesh Standard Time (GMT+6)
        const bdTime = moment.tz("Asia/Dhaka").format("h:mm:ss A"); // e.g. "1:00:00 AM"
        const currentMsg = messages.find(i => i.timer === bdTime);

        // lastSent দিয়ে একই ঘণ্টায় একাধিকবার পাঠানো বন্ধ
        if (currentMsg && lastSent !== bdTime) {
            lastSent = bdTime;
            const randomMsg = currentMsg.msg[Math.floor(Math.random() * currentMsg.msg.length)];
            global.data.allThreadID.forEach(i => o.api.sendMessage(`${randomMsg}\n\n💎 EMon-BHai-BOT`, i));
        }
    }, 1000); // প্রতি সেকেন্ডে চেক, কিন্তু একবারই পাঠাবে
};

